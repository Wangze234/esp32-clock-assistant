// 索引：今天明后 = 0..3，'0'..'9' = 4..13，'/' = 14，'-' = 15，
//       湿 = 16，度 = 17，'%' = 18，离 = 19，线 = 20
//       周 = 21，日 = 22，一 = 23，二 = 24，三 = 25，四 = 26，
//       五 = 27，六 = 28
static inline int wxGlyphIndex(char c) {
  if (c >= '0' && c <= '9') return 4 + (c - '0');
  if (c == '/') return 14;
  if (c == '-') return 15;
  if (c == '%') return 18;
  return -1;
}
